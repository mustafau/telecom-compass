#!/usr/bin/env tsx
/**
 * Prepare an ordinary deployment profile for telecom-api-sandbox.
 * Setup-time only: may fetch catalog/OpenAPI metadata. Runtime never calls /catalog.
 */
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { stringify as stringifyYaml } from "yaml";
import { loadLocalDotenv } from "../src/server/config/load-dotenv";
import { checkProfile } from "../src/server/tmf/profile/check";

loadLocalDotenv();

const DEFAULT_BASE = process.env.LOCAL_TMF_BASE_URL ?? "http://localhost:8787";

type SandboxApiSpec = {
  apiId: string;
  major: "v4" | "v5";
  adapter: string;
  /** Context path including version, e.g. /tmf-api/customer/v5 */
  contextPath: string;
  resourcePath: string;
  responseKind: string;
  operationKey: string;
  /** Prefer this major when both exist. */
  preferred?: boolean;
};

/**
 * Conservative get-by-id operations only. Filtered list queries are intentionally
 * omitted until verified for the target sandbox edition (sandbox rejects unknown filters).
 */
const SANDBOX_GETS: SandboxApiSpec[] = [
  {
    apiId: "TMF629",
    major: "v5",
    adapter: "tmf629-v5",
    contextPath: "/tmf-api/customer/v5",
    resourcePath: "/customer/{id}",
    responseKind: "customer",
    operationKey: "customer.get",
    preferred: true,
  },
  {
    apiId: "TMF637",
    major: "v5",
    adapter: "tmf637-v5",
    contextPath: "/tmf-api/productInventory/v5",
    resourcePath: "/product/{id}",
    responseKind: "product",
    operationKey: "product.get",
  },
  {
    apiId: "TMF638",
    major: "v5",
    adapter: "tmf638-v5",
    contextPath: "/tmf-api/serviceInventory/v5",
    resourcePath: "/service/{id}",
    responseKind: "service",
    operationKey: "service.get",
  },
  {
    apiId: "TMF639",
    major: "v5",
    adapter: "tmf639-v5",
    // Sandbox effective path for TMF639 v5 omits the /tmf-api prefix.
    contextPath: "/resourceInventory/v5",
    resourcePath: "/resource/{id}",
    responseKind: "resource",
    operationKey: "resource.get",
  },
  {
    apiId: "TMF621",
    major: "v5",
    adapter: "tmf621-v5",
    contextPath: "/tmf-api/troubleTicket/v5",
    resourcePath: "/troubleTicket/{id}",
    responseKind: "troubleTicket",
    operationKey: "ticket.get",
  },
  {
    apiId: "TMF641",
    major: "v4",
    adapter: "tmf641-v4",
    contextPath: "/tmf-api/serviceOrdering/v4",
    resourcePath: "/serviceOrder/{id}",
    responseKind: "serviceOrder",
    operationKey: "order.get",
  },
];

async function main(): Promise<void> {
  const baseUrl = (process.argv.find((a, i, all) => all[i - 1] === "--base") ?? DEFAULT_BASE).replace(
    /\/$/,
    "",
  );
  const outDir = path.resolve("config");
  const contractsDir = path.resolve("config/contracts/local");
  await mkdir(contractsDir, { recursive: true });

  console.log(`Probing sandbox at ${baseUrl} (setup-time only)…`);
  let catalogOk = false;
  try {
    const catalog = await fetch(`${baseUrl}/catalog`, {
      headers: { Accept: "application/json" },
      redirect: "error",
      signal: AbortSignal.timeout(5_000),
    });
    catalogOk = catalog.ok;
    if (!catalog.ok) {
      console.warn(`Warning: /catalog returned HTTP ${catalog.status}; continuing with known paths`);
    }
  } catch (error) {
    console.warn(
      `Warning: sandbox not reachable (${error instanceof Error ? error.message : error}). Writing profile with configured base URL; activate only after the backend is up.`,
    );
  }

  const lockEntries: Array<Record<string, unknown>> = [];
  const apis: Record<string, unknown> = {};
  const apiKeyById: Record<string, string> = {
    TMF629: "customer",
    TMF637: "product",
    TMF638: "service",
    TMF639: "resource",
    TMF621: "ticket",
    TMF641: "order",
  };

  for (const spec of SANDBOX_GETS) {
    const contractRef = `sandbox-${spec.apiId.toLowerCase()}-${spec.major}-setup`;
    const specUrl = `${baseUrl}/specs/${spec.apiId}/${spec.major}/openapi.json`;
    let body = JSON.stringify(
      {
        openapi: "3.0.3",
        info: {
          title: `Setup-fetched placeholder for ${spec.apiId} ${spec.major}`,
          version: "setup-local",
          description:
            "Generated by pnpm setup:local when the upstream OpenAPI could not be fetched. Replace by re-running setup against a live sandbox.",
        },
        paths: { [spec.resourcePath]: { get: { responses: { "200": { description: "ok" } } } } },
        "x-compass-setup": { baseUrl, contextPath: spec.contextPath, catalogOk },
      },
      null,
      2,
    );
    let source: "setup-fetched" | "setup-placeholder" = "setup-placeholder";

    try {
      const response = await fetch(specUrl, {
        headers: { Accept: "application/json" },
        redirect: "error",
        signal: AbortSignal.timeout(8_000),
      });
      if (response.ok) {
        body = await response.text();
        source = "setup-fetched";
      } else {
        console.warn(`Could not fetch ${specUrl} (HTTP ${response.status}); using placeholder contract`);
      }
    } catch {
      console.warn(`Could not fetch ${specUrl}; using placeholder contract`);
    }

    if (!body.endsWith("\n")) body += "\n";
    const relativeFile = `config/contracts/local/${spec.apiId}-${spec.major}.openapi.json`;
    await writeFile(path.resolve(relativeFile), body, "utf8");
    const sha256 = createHash("sha256").update(body).digest("hex");
    lockEntries.push({
      contractRef,
      apiId: spec.apiId,
      major: spec.major,
      edition: source === "setup-fetched" ? "sandbox-fetched" : "setup-placeholder",
      sha256,
      file: relativeFile,
      source,
      notes:
        source === "setup-fetched"
          ? `Fetched at setup from ${specUrl}`
          : "Placeholder until sandbox OpenAPI is reachable",
    });

    const key = apiKeyById[spec.apiId]!;
    apis[key] = {
      apiId: spec.apiId,
      major: spec.major,
      contractRef,
      adapter: spec.adapter,
      baseUrl: `${baseUrl}${spec.contextPath}`,
      auth: "fixture",
      operations: {
        [spec.operationKey]: {
          method: "GET",
          path: spec.resourcePath,
          responseKind: spec.responseKind,
        },
      },
    };
  }

  const profile = {
    schemaVersion: 1,
    deployments: [
      {
        id: "telecom-api-sandbox",
        label: "Telecom API Sandbox (local default)",
        environment: "fixture",
        tenantBindings: ["tenant-local"],
        authentication: { fixture: { type: "none" } },
        apis,
        capabilities: {
          customerRead: true,
          productRead: true,
          serviceRead: true,
          resourceRead: true,
          ticketRead: true,
          serviceOrderRead: true,
          // Filtered relationship queries are not declared until verified.
          customerToServices: false,
          serviceToTickets: false,
          serviceToOrders: false,
          knowledgeSearch: false,
        },
        relationships: {},
        extensions: [],
        knowledge: { type: "disabled" },
        limits: {
          maxRelatedRecordsPerKind: 5,
          maxRelationshipDepth: 3,
          maxResponseBytes: 1_048_576,
        },
      },
    ],
  };

  const deploymentsPath = path.join(outDir, "deployments.local.yaml");
  const lockPath = path.join(outDir, "contracts.lock.local.json");
  await writeFile(deploymentsPath, stringifyYaml(profile), "utf8");
  await writeFile(
    lockPath,
    `${JSON.stringify({ schemaVersion: 1, contracts: lockEntries }, null, 2)}\n`,
    "utf8",
  );

  const report = await checkProfile({
    deploymentsFile: deploymentsPath,
    profileId: "telecom-api-sandbox",
    contractLockFile: lockPath,
    repoRoot: process.cwd(),
    offline: true,
  });

  console.log(`Wrote ${deploymentsPath}`);
  console.log(`Wrote ${lockPath}`);
  console.log(`Profile check: ${report.ok ? "ok" : "FAILED"} revision=${report.revision}`);
  if (!report.ok) {
    for (const err of report.errors) console.error(`  - ${err}`);
    process.exit(1);
  }
  console.log(
    "Note: filtered list/relationship capabilities are disabled until verified for this sandbox.",
  );
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
